
STATES = {"SUBMITTED", "DATA_CHECK", "EXTERNAL_CHECKS", "SCORING", "RESULT_READY", "CHECK_ERROR", "SCORING_ERROR"}
TRANSITIONS = {"SUBMITTED":{"DATA_CHECK"}, "DATA_CHECK":{"EXTERNAL_CHECKS","CHECK_ERROR","SCORING_ERROR"}, "EXTERNAL_CHECKS":{"SCORING","CHECK_ERROR"}, "SCORING":{"RESULT_READY","SCORING_ERROR"}, "CHECK_ERROR":{"DATA_CHECK"}, "SCORING_ERROR":{"SCORING"}}
def can_transition(old: str, new: str) -> bool:
    return new in TRANSITIONS.get(old, set())
